/** Maps UserProfile.tierLevel (1 Rookie .. 4 Boss) to a Learning Plan rank. */
export function userPlanRank(tierLevel: number, isLoggedIn: boolean): number {
  if (!isLoggedIn) return -1;
  return Math.min(Math.max(tierLevel - 1, 0), 3);
}

