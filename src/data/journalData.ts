const NEW_CFD_SCENARIO_IDS = ['jr_9', 'jr_10', 'jr_11', 'jr_12', 'jr_13'];

/** Backfill newly added CFD evidence only for untouched built-in demo records. */
export function hydrateDemoCfdEvidence(entries: JournalEntry[]): JournalEntry[] {
  const seed = new Map(JOURNAL_ENTRIES.map(entry => [entry.id, entry]));
  let changed = false;
  let next = entries.map(entry => {
    const demo = seed.get(entry.id);
    if (!demo || entry.accountId || entry.ticketId || entry.source !== demo.source) return entry;
    const patch: Partial<JournalEntry> = {};
    if (entry.initialRisk === undefined && demo.initialRisk !== undefined) patch.initialRisk = demo.initialRisk;
    if (entry.equityAtEntry === undefined && demo.equityAtEntry !== undefined) patch.equityAtEntry = demo.equityAtEntry;
    if (entry.marginAtEntry === undefined && demo.marginAtEntry !== undefined) patch.marginAtEntry = demo.marginAtEntry;
    if (!Object.keys(patch).length) return entry;
    changed = true;
    return { ...entry, ...patch };
  });
  const hasUntouchedDemoSignature = entries.some(entry => entry.id === 'jr_1' && !entry.accountId && !entry.ticketId && entry.source === 'portfolio');
  if (hasUntouchedDemoSignature) {
    const existing = new Set(next.map(entry => entry.id));
    const missingScenarios = NEW_CFD_SCENARIO_IDS.map(id => seed.get(id)).filter((entry): entry is JournalEntry => !!entry && !existing.has(entry.id));
    if (missingScenarios.length) {
      next = [...next, ...missingScenarios];
      changed = true;
    }
  }
  return changed ? next : entries;
}

